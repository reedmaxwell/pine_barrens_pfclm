#!/usr/bin/env python3
"""results/RUNS.md: every scored run, one line each, with a very short note and the KGE at each gage
and the ET bias at each tower.  Notes come from results/run_notes.csv (domain, run, start, change);
scores from results/<domain>/<run>_scores.csv.  Runs without a note are listed so the note can be added.

    python scripts/runs_table.py
"""
import glob
import os
import re
import time

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
SHORT = {"01467000": "Pemberton", "01465850": "Rancocas S", "01466900": "Greenwood", "01464500": "Crosswicks",
         "01409810": "Wading WB", "01410000": "Oswego", "01408500": "Toms", "01409000": "Cedar", "01408900": "Cedar WB",
         "01409280": "Westecunk", "rancocas_north": "Pemberton", "rancocas_south": "Rancocas S", "wading": "Wading", "toms": "Toms", "cedar": "Cedar"}
OBS = {"v1": "WY2008 observed annual means, m3/s: Pemberton 3.27, Rancocas S 1.66, Wading 3.52 (two gages), Toms 4.50, Cedar 2.38.",
       "v2": "WY2008 observed annual means, m3/s: Pemberton 3.27, Rancocas S 1.66, Greenwood 1.91, Crosswicks 2.56, Wading WB 2.67, Oswego 1.88, Toms 4.50, Cedar 2.38, Cedar WB 2.0, Westecunk 0.79."}


def parse(path):
    """{column: value} from one scores file: KGE per gage, bias per tower, plus the streamflow annual bias mean."""
    s = pd.read_csv(path); out = {}
    for q, kge, bias in zip(s["quantity"], s["KGE"], s["bias"]):
        tok = q.split()
        if tok[0] == "streamflow":
            key = tok[1] if tok[1] in SHORT else re.sub(r"[()]", "", tok[2])
            out[f"{SHORT.get(key, key)} KGE"] = kge
        elif tok[0] == "ET":
            out[f"{tok[1]} ET bias"] = bias
    return out


def main():
    notes = pd.read_csv(os.path.join(RES, "run_notes.csv")).set_index(["domain", "run"])
    lines = ["# Pine Barrens runs", "",
             "One line per scored run: where it started, what changed, the KGE at each gage (daily, WY2008) and the ET bias at each AmeriFlux tower (mm/day, model minus tower).",
             "Generated by `scripts/runs_table.py` from `results/run_notes.csv` and the `*_scores.csv` files; edit the notes file, not this one.",
             f"Last built {time.strftime('%Y-%m-%d %H:%M')}.", ""]
    missing = []
    for dom in ("v1", "v2"):
        files = sorted(glob.glob(os.path.join(RES, dom, "*_scores.csv")), key=os.path.getmtime)
        if not files: continue
        rows = []
        for f in files:
            run = os.path.basename(f)[:-len("_scores.csv")]
            note = notes.loc[(dom, run)] if (dom, run) in notes.index else None
            if note is None: missing.append(f"{dom}/{run}")
            row = {"run": run, "date": time.strftime("%m-%d", time.localtime(os.path.getmtime(f))),
                   "start": note["start"] if note is not None else "", "change": note["change"] if note is not None else ""}
            row.update(parse(f)); rows.append(row)
        df = pd.DataFrame(rows)
        order = ["Pemberton", "Rancocas S", "Greenwood", "Crosswicks", "Wading", "Wading WB", "Oswego", "Toms", "Cedar", "Cedar WB", "Westecunk"]
        gcols = sorted([c for c in df.columns if c.endswith("KGE")], key=lambda c: order.index(c[:-4]) if c[:-4] in order else 99)
        cols = ["run", "date", "start", "change"] + gcols + [c for c in df.columns if c.endswith("ET bias")]
        df = df[cols]
        lines += [f"## {dom} ({'gage-clipped, 1,246 cells' if dom == 'v1' else 'complete units, 3,060 cells'})", "", OBS[dom], "",
                  "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for _, r in df.iterrows():
            lines.append("| " + " | ".join(("" if pd.isna(v) else (f"{v:+.2f}" if c.endswith("bias") else f"{v:.2f}")) if isinstance(v, float) else str(v) for c, v in zip(cols, r)) + " |")
        lines.append("")
    out = os.path.join(RES, "RUNS.md"); open(out, "w").write("\n".join(lines)); print("wrote", out)
    if missing: print("no note yet for:", ", ".join(missing))


if __name__ == "__main__":
    main()
